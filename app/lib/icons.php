function icon(string $name, int $size = 20, string $class = ''): string
{
    $paths = icon_paths();
    if (!isset($paths[$name])) {
        return '';
    }
    $classes = trim('icon icon-' . $name . ' ' . $class);
    return '<svg class="' . e($classes) . '" width="' . $size . '" height="' . $size . '" viewBox="0 0 24 24" fill="none" '
        . 'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        . 'aria-hidden="true" focusable="false">' . $paths[$name] . '</svg>';
}

/** Icons exposed to JavaScript renderers (search results, toasts). */
function icons_for_js(array $names): array
{
    $paths = icon_paths();
    $out = [];
    foreach ($names as $name) {
        if (isset($paths[$name])) {
            $out[$name] = $paths[$name];
        }
    }
    return $out;
}
